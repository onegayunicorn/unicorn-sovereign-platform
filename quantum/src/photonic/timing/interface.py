"""Timing hardware interface. Dedicated timing — ordinary NTP is NOT sufficient for coincidence."""
from __future__ import annotations
from abc import ABC, abstractmethod

class TimingHardware(ABC):
    @abstractmethod
    def sync(self) -> bool: ...
    @abstractmethod
    def now_ns(self) -> int: ...
    @abstractmethod
    def clock_drift_ppb(self) -> float: ...
    @abstractmethod
    def holdover_seconds(self) -> float: ...
    @abstractmethod
    def trigger_out(self, channel: int) -> None: ...
